"""Writes tests/stem_reference.hpp from the six-stem song corpus's features_ref.json
(song-corpus/scripts/features.py run over the htdemucs_6s stems of the user's own records): per
group of records and stem, the quartiles and median of the features tests/stem_features.hpp
measures, as song-corpus/scripts/compare.py takes them (numpy percentiles over the tracks that
have the feature). A group of three tracks (the home-psych records' tape-collage passages) has
no quartiles worth the name, so its bounds are its smallest and largest value. Only numbers
leave the corpus; no audio is copied.

    python3 -I tools/stem_gate_profiles.py /path/to/song-corpus/features_ref.json > tests/stem_reference.hpp
"""
import json
import statistics
import sys

GROUPS = {
    'GBV_lofi': (['GBV_lofi'], ['guitar', 'bass', 'other']),
    'OTC': (['OTC'], ['guitar', 'bass', 'other']),
    # The excerpts whose other stem is tape collage rather than an instrument: spectral flatness
    # -73 to -71 dB where the instruments' other stems measure -92 to -135 dB.
    'OTC_collage': (['OTC_Another_Set', 'OTC_I_Won_this_Dog', 'OTC_The_Game_You_Play'], ['other']),
}
FEATURES = ['centroid_hz', 'rolloff85_hz', 'hf_share_db', 'low_share_db', 'flatness_db', 'crest100_db', 'corr', 'wobble_cents']


def percentile(values, q):
    v = sorted(values)
    pos = (len(v) - 1) * q
    lo = int(pos)
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def main():
    ref = json.load(open(sys.argv[1]))
    out = ['// Generated by tools/stem_gate_profiles.py from the six-stem song corpus measured from the user\'s',
           '// own records (htdemucs_6s stems, song-corpus/scripts/features.py). Numbers only. Bounds are the',
           '// quartiles, or for a group of three tracks its smallest and largest value.',
           '#pragma once', '', '#include <array>', '', 'namespace stem {', '',
           'struct Stat { double lo, median, hi; };',
           'struct Reference {',
           '  const char* group;',
           '  const char* stem;',
           '  int tracks;',
           '  Stat ' + ', '.join(FEATURES) + ';',
           '};', '',
           'inline constexpr std::array kReferences{']
    for group, (prefixes, stems) in GROUPS.items():
        items = [v for k, v in ref.items() if any(k.startswith(p) for p in prefixes)]
        q = (0.0, 1.0) if len(items) <= 3 else (0.25, 0.75)
        for stem in stems:
            stats = []
            for f in FEATURES:
                v = [it[stem][f] for it in items if isinstance(it.get(stem, {}).get(f), (int, float))]
                stats.append('{%.4g, %.4g, %.4g}' % (percentile(v, q[0]), statistics.median(v), percentile(v, q[1])))
            out.append('    Reference{"%s", "%s", %d, %s},' % (group, stem, len(items), ', '.join(stats)))
    out += ['};', '', '}  // namespace stem', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
