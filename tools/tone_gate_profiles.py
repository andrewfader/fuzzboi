"""Writes tests/tone_reference.hpp from a guitar-tone corpus's profiles.json: per group of records,
the median and quartiles of the features tests/tone_features.hpp measures, the median
third-octave shape, and the median RMS level of the stems the features were measured on (from
stem_levels.json beside it: spectral flatness floors every bin at an absolute 1e-10, so a render
has to be measured at the level the records' stems were). Only numbers leave the corpus; no audio
is copied.

    python3 -I tools/tone_gate_profiles.py /path/to/guitar-corpus/profiles.json > tests/tone_reference.hpp
"""
import json
import os
import statistics
import sys

# Groups whose separated guitar stems the corpus analysis found unreliable (other instruments in
# the stem, or on near-mono 60s masters the rhythm section folded into it) are not gated against.
SKIP = {'OTC', 'Beatles', 'GBV_all', 'NewYorkPublicLibrary'}
FEATURES = [
    ('centroid_hz', 'features.spectral.centroid_hz'),
    ('rolloff85_hz', 'features.spectral.rolloff85_hz'),
    ('hf_share_db', 'features.spectral.hf_share_above_3k_db'),
    ('flatness_db', 'features.distortion.spectral_flatness_median_db'),
    ('crest100_db', 'features.dynamics.crest_factor_100ms_median_db'),
    ('stereo_corr', 'features.stereo.guitar_stem.corr_200_5k'),
]
NOMINAL = [63, 80, 100, 125, 160, 200, 250, 315, 400, 500, 630, 800, 1000, 1250, 1600, 2000, 2500, 3150,
           4000, 5000, 6300, 8000, 10000, 12500]


def find(profile, key):
    """A group's statistics for one flattened feature key ('spectral.centroid_hz')."""
    return profile['features'][key.replace('features.', '', 1)]


def main():
    data = json.load(open(sys.argv[1]))
    profiles = data['profiles']
    levels = json.load(open(os.path.join(os.path.dirname(sys.argv[1]), 'stem_levels.json')))
    out = ['// Generated by tools/tone_gate_profiles.py from the guitar-tone corpus measured from the user\'s',
           '// own records (htdemucs_6s guitar stems; see guitar-corpus/README.md). Numbers only.',
           '#pragma once', '', '#include <array>', '', 'namespace tone {', '',
           'struct Stat { double q25, median, q75; };',
           'struct Reference {',
           '  const char* group;',
           '  int tracks;',
           '  Stat centroid_hz, rolloff85_hz, hf_share_db, flatness_db, crest100_db, stereo_corr;',
           '  std::array<double, 24> band_db;  // median third-octave shape, 63 Hz to 12.5 kHz',
           '  double stem_rms_dbfs;            // median RMS of the measured stems (mono sum)',
           '};', '',
           'inline constexpr std::array kReferences{']
    for group, p in profiles.items():
        if group in SKIP:
            continue
        stats = []
        for _, key in FEATURES:
            s = find(p, key)
            stats.append('{%.4g, %.4g, %.4g}' % (s['q25'], s['median'], s['q75']))
        bands = ', '.join('%.2f' % find(p, f'features.spectral.band_{n}Hz_db')['median'] for n in NOMINAL)
        n = find(p, FEATURES[0][1])['n']
        level = statistics.median(v['rms_dbfs'] for v in levels.values() if v['group'] == group)
        out.append('    Reference{"%s", %d, %s,\n              {%s}, %.2f},' % (group, n, ', '.join(stats), bands, level))
    out += ['};', '', '}  // namespace tone', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
