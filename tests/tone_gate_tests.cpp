// The quality gate against real records: each physical preset written for a kind of record plays
// a phrase in that style, and its tone is measured exactly as the reference corpus measured the
// separated guitar stems of the user's own records (tests/tone_features.hpp, checked number for
// number against the corpus analysis with tools/tone_measure.cpp). Each measure has to land where
// that group's records do: inside its interquartile range widened by 0.75 of it on each side
// (about the 10th to 90th percentile of its tracks), and its third-octave shape from 100 Hz to
// 8 kHz within 4 dB on average of the group's median shape.
//
// The references (tests/tone_reference.hpp) are numbers only, generated by
// tools/tone_gate_profiles.py; no audio from the records is in the repository.
// Scenarios: features/tone_gate.feature.
//
//   tone_gate_tests [preset-name-filter]   (prints every preset's measures either way)

#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include "spec.hpp"
#include "tone_gate.hpp"

using namespace tone_gate;

namespace {
const char* g_filter = nullptr;
}  // namespace

SCENARIO(each_records_preset_sounds_like_the_records) {
  GIVEN("each physical preset written for a group of records, playing sixteen seconds in that style at 120 BPM");
  THEN("its centroid, roll-off, share above 3 kHz, flatness, 100 ms crest and L/R correlation each land within the group's quartiles widened by 0.75 IQR, and its third-octave shape within 4 dB on average of the group's");
  std::printf("    %-30s %-22s %7s %7s %7s %7s %6s %6s %6s\n", "preset", "records", "cent", "roll", "hf dB", "flat", "crest", "corr", "shape");
  for (const Case& c : cases()) {
    if (g_filter && !std::strstr(c.preset, g_filter)) continue;
    const long index = preset_index(c.preset);
    const tone::Reference* ref = reference(c.group);
    CHECK(index >= 0, std::string("preset exists: ") + c.preset);
    CHECK(ref != nullptr, std::string("reference group ") + c.group);
    if (index < 0 || !ref) continue;
    auto s = fuzzboi::Settings::defaults();
    fuzzboi::presets::apply(static_cast<size_t>(index), s.v.data());
    const tone::Features f = measure_case(s, c.phrase, ref->stem_rms_dbfs);
    const Verdict v = judge(f, *ref, c);
    std::printf("    %-30s %-22s %7.0f %7.0f %7.1f %7.1f %6.1f %6.2f %6.1f %s\n", c.preset, c.group, f.centroid_hz, f.rolloff85_hz,
                f.hf_share_db, f.flatness_db, f.crest100_db, f.stereo_corr, v.shape_db, v.failures.empty() ? "ok" : "FAIL");
    std::printf("    %-30s %-22s %7.0f %7.0f %7.1f %7.1f %6.1f %6.2f   (records' medians)\n", "", "", ref->centroid_hz.median,
                ref->rolloff85_hz.median, ref->hf_share_db.median, ref->flatness_db.median, ref->crest100_db.median, ref->stereo_corr.median);
    if (std::getenv("TONE_GATE_BANDS")) {
      std::printf("      bands - records (100 Hz .. 8 kHz):");
      for (int b = 2; b <= 21; ++b) std::printf(" %+.0f", f.band_db[static_cast<size_t>(b)] - ref->band_db[static_cast<size_t>(b)]);
      std::printf("\n");
    }
    if (c.flatness_allowance_db > 0.0 || c.hf_allowance_db > 0.0)
      std::printf("      (allowance: flatness %.1f dB lower, share above 3 kHz %.1f dB higher than the records' range)\n",
                  c.flatness_allowance_db, c.hf_allowance_db);
    CHECK(v.failures.empty(), std::string(c.preset) + ": " + v.failures);
  }
}

int main(int argc, char** argv) {
  if (argc > 1 && argv[1][0] != '-') g_filter = argv[1];
  return spec::run(1, argv);
}
