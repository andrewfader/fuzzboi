// The quality gate against real records: each physical preset written for a kind of record plays
// a phrase in that style, and its tone is measured exactly as the reference corpus measured the
// separated guitar stems of the user's own records (tests/tone_features.hpp, checked number for
// number against the corpus analysis with tools/tone_measure.cpp). Each measure has to land where
// that group's records do: inside its interquartile range widened by 0.75 of it on each side
// (about the 10th to 90th percentile of its tracks), and its third-octave shape from 100 Hz to
// 8 kHz within 4 dB on average of the group's median shape.
//
// The references (tests/tone_reference.hpp) are numbers only, generated by
// tools/tone_gate_profiles.py; no audio from the records is in the repository.
// The stem gate holds the presets written for the lo-fi and home-psych records of the six-stem
// song corpus (tests/stem_reference.hpp, generated by tools/stem_gate_profiles.py) to the plain
// interquartile range of the stem each would be separated into, measured as that corpus measures
// a stem (tests/stem_features.hpp), tape wobble included.
// Scenarios: features/tone_gate.feature.
//
//   tone_gate_tests [preset-name-filter]   (prints every preset's measures either way)

#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include "spec.hpp"
#include "stem_gate.hpp"
#include "tone_gate.hpp"

using namespace tone_gate;

namespace {
const char* g_filter = nullptr;
}  // namespace

SCENARIO(each_records_preset_sounds_like_the_records) {
  GIVEN("each physical preset written for a group of records, playing sixteen seconds in that style at 120 BPM");
  THEN("its centroid, roll-off, share above 3 kHz, flatness, 100 ms crest and L/R correlation each land within the group's quartiles widened by 0.75 IQR, and its third-octave shape within 4 dB on average of the group's");
  std::printf("    %-30s %-22s %7s %7s %7s %7s %6s %6s %6s\n", "preset", "records", "cent", "roll", "hf dB", "flat", "crest", "corr", "shape");
  for (const Case& c : cases()) {
    if (g_filter && !std::strstr(c.preset, g_filter)) continue;
    const long index = preset_index(c.preset);
    const tone::Reference* ref = reference(c.group);
    CHECK(index >= 0, std::string("preset exists: ") + c.preset);
    CHECK(ref != nullptr, std::string("reference group ") + c.group);
    if (index < 0 || !ref) continue;
    auto s = fuzzboi::Settings::defaults();
    fuzzboi::presets::apply(static_cast<size_t>(index), s.v.data());
    const tone::Features f = measure_case(s, c.phrase, ref->stem_rms_dbfs);
    const Verdict v = judge(f, *ref, c);
    std::printf("    %-30s %-22s %7.0f %7.0f %7.1f %7.1f %6.1f %6.2f %6.1f %s\n", c.preset, c.group, f.centroid_hz, f.rolloff85_hz,
                f.hf_share_db, f.flatness_db, f.crest100_db, f.stereo_corr, v.shape_db, v.failures.empty() ? "ok" : "FAIL");
    std::printf("    %-30s %-22s %7.0f %7.0f %7.1f %7.1f %6.1f %6.2f   (records' medians)\n", "", "", ref->centroid_hz.median,
                ref->rolloff85_hz.median, ref->hf_share_db.median, ref->flatness_db.median, ref->crest100_db.median, ref->stereo_corr.median);
    if (std::getenv("TONE_GATE_BANDS")) {
      std::printf("      bands - records (100 Hz .. 8 kHz):");
      for (int b = 2; b <= 21; ++b) std::printf(" %+.0f", f.band_db[static_cast<size_t>(b)] - ref->band_db[static_cast<size_t>(b)]);
      std::printf("\n");
    }
    if (c.flatness_allowance_db > 0.0 || c.hf_allowance_db > 0.0 || c.shape_allowance_db > 0.0)
      std::printf("      (allowance: flatness %.1f dB lower, share above 3 kHz %.1f dB beyond the records' range, shape %.1f dB over the limit)\n",
                  c.flatness_allowance_db, c.hf_allowance_db, c.shape_allowance_db);
    CHECK(v.failures.empty(), std::string(c.preset) + ": " + v.failures);
  }
}

SCENARIO(each_stem_preset_lands_in_its_groups_quartiles) {
  GIVEN("each preset written for the lo-fi or home-psych records' guitar, bass or other stem, playing sixteen seconds of its part at 120 BPM");
  THEN("measured as that stem, its centroid and roll-off (and a guitar's L/R correlation, and a guitar's or other stem's tape wobble in cents) lie inside the group's interquartile range");
  THEN("and a tape collage's centroid, roll-off, flatness, crest, L/R correlation and wobble lie inside the range of the records' collage passages");
  for (const stem_gate::Case& c : stem_gate::cases()) {
    if (g_filter && !std::strstr(c.preset, g_filter)) continue;
    const long index = preset_index(c.preset);
    const stem::Reference* ref = stem_gate::reference(c.group, c.stem);
    CHECK(index >= 0, std::string("preset exists: ") + c.preset);
    CHECK(ref != nullptr, std::string("reference ") + c.group + " " + c.stem);
    if (index < 0 || !ref) continue;
    auto s = fuzzboi::Settings::defaults();
    fuzzboi::presets::apply(static_cast<size_t>(index), s.v.data());
    const auto audio = stem_gate::render_case(s, c.phrase);
    const stem::Features f = stem::measure(audio.left, audio.right, kRate);
    const std::string failures = stem_gate::judge(f, *ref);
    std::printf("    %-30s %-11s %-6s cent %5.0f [%4.0f..%4.0f] roll %5.0f [%4.0f..%4.0f] flat %6.1f [%.1f..%.1f] crest %4.1f [%.1f..%.1f] corr %.2f [%.2f..%.2f] wobble %5.2f [%.2f..%.2f] %s\n",
                c.preset, c.group, c.stem, f.centroid_hz, ref->centroid_hz.lo, ref->centroid_hz.hi, f.rolloff85_hz, ref->rolloff85_hz.lo,
                ref->rolloff85_hz.hi, f.flatness_db, ref->flatness_db.lo, ref->flatness_db.hi, f.crest100_db, ref->crest100_db.lo, ref->crest100_db.hi,
                f.corr, ref->corr.lo, ref->corr.hi, f.wobble_cents, ref->wobble_cents.lo, ref->wobble_cents.hi, failures.empty() ? "ok" : "FAIL");
    CHECK(failures.empty(), std::string(c.preset) + ": " + failures);
  }
}

SCENARIO(the_master_tape_machine_puts_tape_wobble_on_any_source) {
  struct Source { const char* preset; tone::Phrase phrase; };
  for (const Source& src : {Source{"4-track crunch (phys)", tone::Phrase::Drone}, Source{"Bright Vox organ", tone::Phrase::Pad}}) {
    GIVEN(std::string("\"") + src.preset + "\" with the master tape machine's wow and flutter off");
    auto s = fuzzboi::Settings::defaults();
    fuzzboi::presets::apply(static_cast<size_t>(preset_index(src.preset)), s.v.data());
    s.v[fuzzboi::params::kMachineWow] = 0.0;
    s.v[fuzzboi::params::kMachineFlutter] = 0.0;
    const auto dry = stem_gate::render_case(s, src.phrase);
    const double still = stem::measure(dry.left, dry.right, kRate).wobble_cents;
    WHEN("the machine's flutter is turned to 55%");
    s.v[fuzzboi::params::kMachineFlutter] = 0.55;
    const auto taped = stem_gate::render_case(s, src.phrase);
    const double wobble = stem::measure(taped.left, taped.right, kRate).wobble_cents;
    THEN("the pitch wobbles by several cents more, as the records' tape does");
    CHECK(still < 2.5, spec::fmt("wobble without the machine's flutter %.2f cents", still));
    CHECK(wobble > 4.0 && wobble - still > 2.5, spec::fmt("wobble with it %.2f cents (without %.2f)", wobble, still));
  }
}

SCENARIO(the_home_tape_found_sounds_waver_as_a_cassette_does) {
  GIVEN("\"Home-psych tape collage\" holding one long note a bar, with the master tape machine's wow and flutter off");
  auto s = fuzzboi::Settings::defaults();
  fuzzboi::presets::apply(static_cast<size_t>(preset_index("Home-psych tape collage")), s.v.data());
  s.v[fuzzboi::params::kMachineWow] = 0.0;
  s.v[fuzzboi::params::kMachineFlutter] = 0.0;
  const stem::Reference* collage = stem_gate::reference("OTC_collage", "other");
  const auto wobble = [&](int bank) {
    s.v[fuzzboi::params::kFoundSounds] = bank;
    const auto audio = stem_gate::render_case(s, tone::Phrase::Air);
    return stem::measure(audio.left, audio.right, kRate).wobble_cents;
  };
  WHEN("the empty slots play the shortwave found sounds, then the home-tape ones");
  const double shortwave = wobble(0), home = wobble(1);
  THEN("the shortwave whistle's warble reads over 12 cents, and the home tape's own wow and flutter inside the records' collage range");
  CHECK(shortwave > 12.0, spec::fmt("shortwave wobble %.2f cents", shortwave));
  CHECK(home >= collage->wobble_cents.lo && home <= collage->wobble_cents.hi,
        spec::fmt("home tape wobble %.2f cents, records' collage %.2f..%.2f", home, collage->wobble_cents.lo, collage->wobble_cents.hi));
}

int main(int argc, char** argv) {
  if (argc > 1 && argv[1][0] != '-') g_filter = argv[1];
  return spec::run(1, argv);
}
